param(
 [string]$CategoryDatabase = 'baocao.sct.cenit.vn.cate',
 [string]$ReportDatabase = 'baocao.sct.cenit.vn',
 [string]$OutputDirectory,
 [string]$RoleMappingPath = (Join-Path $PSScriptRoot "../../CenIT.ReportTourism.WebApp/Configs/AppSettings.config"),
 [string]$OutputPath = (Join-Path $PSScriptRoot '../Deploy_SCT_IndustryChatbot.sql'),
 [string]$PerformanceIndexOutputPath = (Join-Path $PSScriptRoot '../Deploy_SCT_ReportPerformanceIndexes.sql')
)
$ErrorActionPreference = 'Stop'
$root = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$category = $CategoryDatabase
$report = $ReportDatabase
 . (Join-Path $PSScriptRoot 'ReportDeployment.Common.ps1')
Assert-ReportDatabaseNames $category $report
$roles=Read-ReportRoleMapping $RoleMappingPath
$roleValues=Get-ReportRoleValues $roles
function RetargetSource([string]$value) {
 return Convert-ReportDatabaseReferences $value $category $report
}
$customTarget=($category -ne 'baocao.sct.cenit.vn.cate' -or $report -ne 'baocao.sct.cenit.vn')
if ($customTarget -and !$OutputDirectory) { throw 'Specify OutputDirectory for another target; do not overwrite the SCT release.' }
if ($OutputDirectory) {
 $null=New-Item -ItemType Directory -Path $OutputDirectory -Force
 $OutputDirectory=[IO.Path]::GetFullPath($OutputDirectory)
 $OutputPath=Join-Path $OutputDirectory 'Deploy_IndustryChatbot.sql'
 $PerformanceIndexOutputPath=Join-Path $OutputDirectory 'Deploy_ReportPerformanceIndexes.sql'
}
$checkDirectory=Split-Path ([IO.Path]::GetFullPath($OutputPath))
$checkSuffix=if ($OutputDirectory) { '' } else { '_SCT' }
& (Join-Path $PSScriptRoot 'Build_ReportDeploymentChecks.ps1') -CategoryDatabase $category -ReportDatabase $report `
 -RoleMappingPath $RoleMappingPath -PreflightPath (Join-Path $checkDirectory ('Preflight'+$checkSuffix+'_IndustryChatbot.sql')) `
 -VerifyPath (Join-Path $checkDirectory ('Verify'+$checkSuffix+'_IndustryChatbot.sql'))
$preflightName='Preflight'+$checkSuffix+'_IndustryChatbot.sql'
$preflightBody=[regex]::Replace([IO.File]::ReadAllText((Join-Path $checkDirectory $preflightName)),'(?im)^:ON ERROR EXIT\s*$','')
$parts = New-Object 'System.Collections.Generic.List[string]'
$parts.Add(@"
-- Generated by Scripts/Build_SCT_IndustryChatbot_Deployment.ps1.
-- TARGETS: [$category] and [$report] on the connected SQL Server.
-- Run with sqlcmd -b, or SSMS SQLCMD Mode. Stop application traffic first.
-- SQLCMD error-exit disconnects and rolls back this transaction on a failed batch.
-- Review definitions/backups first. Existing user industry grants are preserved.
:ON ERROR EXIT
SET XACT_ABORT ON;
IF DB_ID(N'$category') IS NULL OR DB_ID(N'$report') IS NULL
 THROW 50120,'Expected deployment databases are missing.',1;
IF EXISTS(SELECT 1 FROM sys.databases WHERE name IN(N'$category',N'$report') AND compatibility_level<110)
 THROW 50121,'Database compatibility level 110 or higher is required.',1;
GO
$preflightBody
GO
BEGIN TRANSACTION;
GO
"@)
$parts.Add((RetargetSource ([IO.File]::ReadAllText((Join-Path $root '2. New Report Permission/00_RoleMapping.sql')))))
$parts.Add(@"
USE [$category];
GO
DECLARE @Mapping TABLE(SemanticKey varchar(80),RoleId int,ScopeMode varchar(10),IsIndustryEditorTarget bit);
INSERT @Mapping VALUES $roleValues;
-- Replace only release-owned mapping rows, never Sys_Roles, permissions or user grants.
DELETE FROM dbo.Report_RoleMappings;
INSERT dbo.Report_RoleMappings SELECT * FROM @Mapping;
GO
"@)
foreach ($file in @('01_CategoryPermissions.sql','02_ReportScope.sql','03_ScopedReportProcedures.sql','06_DataImportOperations.sql')) {
    $parts.Add((RetargetSource ([IO.File]::ReadAllText((Join-Path $root ('2. New Report Permission/' + $file))))))
}
foreach ($entry in @(
    @('category','f_Chatbot_UserScope.sql'),
    @('category','f_Chatbot_AuthorizedEnterprises.sql'),
    @('category','p_Cate_Chatbot_EnterpriseScope.sql'),
    @('category','p_Cate_Chatbot_EnterpriseProducts.sql'),
    @('report','p_Report_Chatbot_Snapshot.sql'),
    @('report','p_Report_Chatbot_Summary.sql'),
    @('report','p_Report_Chatbot_FilterOptions.sql'),
    @('report','p_Report_Chatbot_ProgressDetails.sql'),
    @('report','p_Report_Chatbot_IndicatorData.sql'),
    @('report','p_Report_Chatbot_Metadata.sql'),
    @('report','p_Report_Chatbot_ReportFiles.sql')
)) {
    $target = if ($entry[0] -eq 'category') { $category } else { $report }
    $body = RetargetSource ([IO.File]::ReadAllText((Join-Path $root ('Chatbot/' + $entry[1]))))
    $match = [regex]::Match($body, '(?im)^CREATE\s+(FUNCTION|PROCEDURE)\s+dbo\.(\w+)')
    if (!$match.Success) { throw ('Unrecognized SQL contract: ' + $entry[1]) }
    $alter = [regex]::Replace($body, '(?im)^CREATE\s+(FUNCTION|PROCEDURE)', 'ALTER $1')
    $createSql = $body.Replace("'", "''")
    $alterSql = $alter.Replace("'", "''")
    $name = $match.Groups[2].Value
    $parts.Add("USE [$target];`r`nGO`r`nIF OBJECT_ID(N'dbo.$name') IS NULL`r`n EXEC(N'$createSql');`r`nELSE`r`n EXEC(N'$alterSql');`r`nGO")
}
$parts.Add("USE [$category];`r`nGO")
$parts.Add([IO.File]::ReadAllText((Join-Path $root 'Scripts/Seed_Dashboard_SysMessages.sql')))
$parts.Add([IO.File]::ReadAllText((Join-Path $root 'Scripts/Seed_UserIndustryPermissions_SysMessages.sql')))
$parts.Add("`r`nGO`r`nIF XACT_STATE()<>1 THROW 50122,'Deployment transaction is not committable.',1;`r`nCOMMIT TRANSACTION;`r`nGO")
$sql = $parts -join "`r`nGO`r`n"
[IO.File]::WriteAllText([IO.Path]::GetFullPath($OutputPath), $sql, (New-Object System.Text.UTF8Encoding($true)))
Write-Output ('Generated ' + [IO.Path]::GetFullPath($OutputPath))
$indexes = [IO.File]::ReadAllText((Join-Path $root '2. New Report Permission/04_PerformanceIndexes.sql'))
$indexes = RetargetSource $indexes
$indexHeader = @"
-- Generated by Scripts/Build_SCT_IndustryChatbot_Deployment.ps1.
-- Separate SCT performance migration. Review space/backups; pause traffic.
-- Offline index builds may block. Rerunnable; does not change rows or grants.
:ON ERROR EXIT
SET XACT_ABORT ON;
IF DB_ID(N'$category') IS NULL OR DB_ID(N'$report') IS NULL
 THROW 50120,'Expected deployment databases are missing.',1;
GO
$preflightBody
GO
"@
[IO.File]::WriteAllText([IO.Path]::GetFullPath($PerformanceIndexOutputPath), ($indexHeader + "`r`n" + $indexes), (New-Object System.Text.UTF8Encoding($true)))
Write-Output ('Generated ' + [IO.Path]::GetFullPath($PerformanceIndexOutputPath))

# One server batch works in DataGrip as well as sqlcmd. Lower-level compilation
# errors from sp_executesql reach the outer CATCH, independently of client settings.
# Indexes, definitions, mappings and labels commit only after verification succeeds.
$allPath=Join-Path $checkDirectory $(if ($OutputDirectory) { 'Deploy_All.sql' } else { 'Deploy_SCT_All.sql' })
$verifyName='Verify'+$checkSuffix+'_IndustryChatbot.sql'
$allParts=@(
 [IO.File]::ReadAllText((Join-Path $checkDirectory $preflightName)),
 [IO.File]::ReadAllText([IO.Path]::GetFullPath($PerformanceIndexOutputPath)),
 [IO.File]::ReadAllText([IO.Path]::GetFullPath($OutputPath)),
 [IO.File]::ReadAllText((Join-Path $checkDirectory $verifyName))
)
$all=New-Object 'Collections.Generic.List[string]'
$all.Add(@"
-- Generated SCT release for [$category] and [$report].
-- Execute this entire file as ONE statement in a dedicated DataGrip/sqlcmd connection.
-- No SQLCMD mode required. Back up definitions and stop application traffic/jobs first.
-- Offline index builds may block; all changes remain in one transaction through verification.
SET NOCOUNT ON;
SET XACT_ABORT ON;
IF @@TRANCOUNT<>0 THROW 50125,'Use a dedicated connection with no open transaction.',1;
IF DB_ID(N'$category') IS NULL OR DB_ID(N'$report') IS NULL
 THROW 50120,'Expected deployment databases are missing or inaccessible.',1;
BEGIN TRY
 BEGIN TRANSACTION;
"@)
$batchDatabase=$report
foreach ($batch in [regex]::Split(($allParts -join "`r`nGO`r`n"),'(?im)^\s*GO\s*$')) {
 $body=[regex]::Replace($batch,'(?im)^:ON ERROR EXIT\s*$','').Trim()
 if (!$body) { continue }
 # The combined script owns the transaction; individual component scripts retain
 # their original standalone transaction boundaries.
 if ($body -match '^BEGIN TRANSACTION;\s*$' -or
     $body -match "^IF XACT_STATE\(\)<>1 THROW 50122,'Deployment transaction is not committable\.',1;\s*COMMIT TRANSACTION;\s*$") { continue }
 $use=[regex]::Match($body,'(?im)^USE \[([^\]]+)\];?\s*$')
 if ($use.Success) {
  $batchDatabase=$use.Groups[1].Value
  if ($batchDatabase -notin @($category,$report)) { throw 'Unexpected combined-script database context.' }
 }
 # A database-qualified sp_executesql preserves each original batch's context and
 # lets ALTER PROCEDURE/FUNCTION remain the first statement in its own batch.
 $all.Add(" EXEC [$batchDatabase].sys.sp_executesql N'"+$body.Replace("'","''")+"';")
}
$all.Add(@"
 IF XACT_STATE()<>1 THROW 50122,'Deployment transaction is not committable.',1;
 COMMIT TRANSACTION;
END TRY
BEGIN CATCH
 IF XACT_STATE()<>0 ROLLBACK TRANSACTION;
 THROW;
END CATCH;
"@)
$allSql=[regex]::Replace(($all -join "`r`n"),'(?m)[ \t]+(?=\r?$)','')
[IO.File]::WriteAllText($allPath,$allSql,(New-Object System.Text.UTF8Encoding($true)))
Write-Output ('Generated '+$allPath)
if ($OutputDirectory) {
 $artifacts=Get-ChildItem -LiteralPath $OutputDirectory -File | Where-Object { $_.Extension -eq '.sql' -or $_.Name -in @('sql-object-manifest.json') } | Sort-Object Name
 $manifest=@($artifacts | ForEach-Object { [ordered]@{ file=$_.Name; sha256=(Get-FileHash -LiteralPath $_.FullName -Algorithm SHA256).Hash } })
 [IO.File]::WriteAllText((Join-Path $OutputDirectory 'artifact-hashes.json'),(ConvertTo-Json -InputObject $manifest -Depth 4))
}
